import { resolveUserDisplayName } from '@/lib/report-history-utils';

export interface AuditChangeLogRow {
  id: string;
  userId: string;
  action: string;
  detail?: Record<string, unknown> | null;
  createdAt: string;
}

export interface AuditChangeEvent {
  id: string;
  label: string;
  sublabel?: string;
  createdAt: string;
}

function formatAuditAction(
  row: AuditChangeLogRow,
  nameMap: Map<string, string>,
): AuditChangeEvent {
  const name = resolveUserDisplayName(nameMap, row.userId);
  const detail = row.detail ?? {};

  switch (row.action) {
    case 'AUDIT_CREATED':
      return { id: row.id, label: `Audit created by ${name}`, createdAt: row.createdAt };
    case 'AUDIT_STARTED':
      return { id: row.id, label: `Audit started by ${name}`, createdAt: row.createdAt };
    case 'AUDIT_COMPLETED':
      return { id: row.id, label: `Audit completed by ${name}`, createdAt: row.createdAt };
    case 'AUDIT_CANCELLED':
      return { id: row.id, label: `Audit cancelled by ${name}`, createdAt: row.createdAt };
    case 'AUDIT_UPDATED': {
      const fields = Object.keys(detail);
      const sublabel =
        fields.length > 0
          ? fields.map((f) => f.replace(/_/g, ' ')).join(', ')
          : undefined;
      return {
        id: row.id,
        label: `Audit details updated by ${name}`,
        sublabel,
        createdAt: row.createdAt,
      };
    }
    case 'FINDING_ADDED':
      return { id: row.id, label: `Finding added by ${name}`, createdAt: row.createdAt };
    case 'CHECKLIST_GENERATED':
    case 'CHECKLIST_REPLACED': {
      const count = detail.count as number | undefined;
      return {
        id: row.id,
        label: `Checklist ${row.action === 'CHECKLIST_REPLACED' ? 'replaced' : 'generated'} by ${name}`,
        sublabel: count != null ? `${count} items` : undefined,
        createdAt: row.createdAt,
      };
    }
    case 'CHECKLIST_AI_EVIDENCE':
      return { id: row.id, label: `AI evidence generated by ${name}`, createdAt: row.createdAt };
    case 'NC_CREATED_FROM_CHECKLIST':
      return { id: row.id, label: `Non-conformity created from checklist by ${name}`, createdAt: row.createdAt };
    default:
      return {
        id: row.id,
        label: `${row.action.replace(/_/g, ' ').toLowerCase()} by ${name}`,
        createdAt: row.createdAt,
      };
  }
}

export function buildAuditChangeEvents(
  logs: AuditChangeLogRow[],
  nameMap: Map<string, string>,
): AuditChangeEvent[] {
  const sorted = [...logs].sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
  );
  const events: AuditChangeEvent[] = [];
  let i = 0;

  while (i < sorted.length) {
    const row = sorted[i];
    if (row.action === 'CHECKLIST_UPDATED') {
      const batch = [row];
      let j = i + 1;
      while (j < sorted.length) {
        const next = sorted[j];
        if (next.action !== 'CHECKLIST_UPDATED' || next.userId !== row.userId) break;
        const dt = Math.abs(
          new Date(row.createdAt).getTime() - new Date(next.createdAt).getTime(),
        );
        if (dt > 5000) break;
        batch.push(next);
        j++;
      }
      const name = resolveUserDisplayName(nameMap, row.userId);
      const count = batch.length;
      events.push({
        id: `checklist-batch-${row.id}`,
        label:
          count === 1
            ? `Checklist criterion updated by ${name}`
            : `${count} criteria updated by ${name}`,
        createdAt: row.createdAt,
      });
      i = j;
      continue;
    }

    events.push(formatAuditAction(row, nameMap));
    i++;
  }

  return events;
}
